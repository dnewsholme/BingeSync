let currentLanguage = 'en';

export function getLanguage() {
  const saved = localStorage.getItem('bingesync_language');
  if (saved && translations[saved]) {
    return saved;
  }
  const browser = (navigator.language || navigator.userLanguage || '').slice(0, 2).toLowerCase();
  if (translations[browser]) {
    return browser;
  }
  return 'en';
}

export function t(key, params = {}) {
  const dict = translations[currentLanguage] || translations.en;
  let text = dict[key] || translations.en[key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return text;
}

export function getMonthName(monthIndex) {
  try {
    const d = new Date(2024, monthIndex, 1);
    const name = d.toLocaleDateString(currentLanguage, { month: 'long' });
    return name.charAt(0).toUpperCase() + name.slice(1);
  } catch (e) {
    const fallbacks = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
    return fallbacks[monthIndex] || 'Month';
  }
}

export function getMonthShortName(monthIndex) {
  try {
    const d = new Date(2024, monthIndex, 1);
    const name = d.toLocaleDateString(currentLanguage, { month: 'short' });
    return name.charAt(0).toUpperCase() + name.slice(1);
  } catch (e) {
    const fallbacks = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    return fallbacks[monthIndex] || 'M';
  }
}

export function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  currentLanguage = lang;
  localStorage.setItem('bingesync_language', lang);
  document.documentElement.lang = lang;

  // Translate all DOM elements with data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const k = node.getAttribute('data-i18n');
    const translated = t(k);
    if (translated && translated !== k) {
      node.textContent = translated;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const k = node.getAttribute('data-i18n-placeholder');
    const translated = t(k);
    if (translated && translated !== k) {
      node.placeholder = translated;
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach((node) => {
    const k = node.getAttribute('data-i18n-title');
    const translated = t(k);
    if (translated && translated !== k) {
      node.title = translated;
    }
  });

  // Sync any language selector dropdowns
  document.querySelectorAll('.language-select').forEach((sel) => {
    sel.value = lang;
  });

  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

export function initI18n() {
  currentLanguage = getLanguage();
  setLanguage(currentLanguage);
}
